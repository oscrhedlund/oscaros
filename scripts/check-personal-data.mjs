import {readFileSync} from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const schemaSource=readFileSync('lib/store-schema.ts','utf8');
const schemaJS=ts.transpileModule(schemaSource,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace("from 'zod'",`from '${new URL('../node_modules/zod/index.js',import.meta.url)}'`);
const schemaURL='data:text/javascript;base64,'+Buffer.from(schemaJS).toString('base64');
const source=readFileSync('lib/personal-data.ts','utf8').replace("'./store-schema'",JSON.stringify(schemaURL));
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const model=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const d=model.seed();
assert.equal(d.items.filter(i=>i.focus).length,2);
assert.ok(d.items.every(i=>i.id&&i.title));
assert.equal(new Set(d.items.map(i=>i.id)).size,d.items.length);
assert.ok(d.goals.every(g=>g.taskIds.every(id=>d.items.some(i=>i.id===id))));
assert.equal(model.makeItem('Test').kind,'capture');
assert.equal(model.makeItem('Test','task').due,model.day());
assert.equal(model.habitStats({days:[model.offset(-1),model.offset(-2)]}).streak,2);
let raw=null;globalThis.localStorage={getItem:()=>raw,setItem:(k,v)=>{raw=v}};
assert.equal(model.storage.load(),null);
model.storage.save(d);assert.deepEqual(model.storage.load(),d);
raw='{"version":2}';assert.throws(()=>model.storage.load());
console.log('Passed: seed integrity, goal links, capture defaults, task dates, habit streak, storage roundtrip and invalid version.');
